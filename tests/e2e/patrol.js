const { chromium } = require('playwright');
const { execSync } = require('child_process');
const B = 'http://localhost:3000';
const q = (sql) => execSync(`psql -At -U root -h /var/run/postgresql d5dev -c "${sql}"`).toString().trim();
const res = [];
const t = (n, ok, x = '') => { res.push(ok); console.log((ok ? 'PASS ' : 'FAIL ') + n + (x ? '  ' + x : '')); };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext();
  const a = await ctx.newPage();
  const c = await ctx.newPage();
  await a.goto(B + '/dev-login');
  await a.click('form:has(input[value="hcso_member"]) button');
  await a.waitForURL(/\/hub/);
  const row = () => q("select duty_status||'|'||coalesce(duty_changed_at::text,'') from memberships m join auth.users u on u.id=m.profile_id where u.email like 'hcso_member%' and department_key='hcso'");
  await a.goto(B + '/hub/patrol');
  await c.goto(B + '/hub/patrol');
  t('starts off duty', row().startsWith('off_duty'), row());
  await a.click('form:has(input[value="on_duty"]) button');
  await a.waitForLoadState('networkidle');
  const first = row();
  t('start puts member on duty', first.startsWith('on_duty'), first);
  await new Promise((r) => setTimeout(r, 1500));
  await c.click('form:has(input[value="on_duty"]) button');
  await c.waitForLoadState('networkidle');
  t('second Start from a stale tab does not reset the clock', row() === first, row());
  await a.goto(B + '/hub/patrol');
  await a.waitForTimeout(1500);
  const txt = await a.evaluate(() => document.body.innerText);
  const m = txt.match(/(\d\d):(\d\d):(\d\d)/);
  t('refresh keeps the patrol running', !!m);
  const secs = m ? +m[1] * 3600 + +m[2] * 60 + +m[3] : -1;
  t('elapsed time comes from the stored start', secs >= 2 && secs < 60, String(secs) + 's');
  await a.locator('form:has(input[value="off_duty"]) button').first().click();
  await a.waitForTimeout(600);
  const dlg = a.locator('dialog[open] button[type=submit], dialog[open] button:has-text("End")').first();
  if (await dlg.count()) await dlg.click();
  await a.waitForURL(/shifts\/new/, { timeout: 8000 }).catch(() => {});
  t('end opens the prefilled logger', /shifts\/new/.test(a.url()), a.url().replace(B, '').slice(0, 70));
  t('end puts member off duty', row().startsWith('off_duty'), row());
  // the stale second tab still shows End: ending again must not stamp a second log
  const stale = await c.locator('form:has(input[value="off_duty"])').count();
  const before = row();
  if (stale) {
    await c.locator('form:has(input[value="off_duty"]) button').first().click();
    await c.waitForTimeout(600);
    const d2 = c.locator('dialog[open] button[type=submit], dialog[open] button:has-text("End")').first();
    if (await d2.count()) await d2.click();
    await c.waitForLoadState('networkidle');
    t('ending twice does not open a second log or change the record', !/shifts\/new/.test(c.url()) && row() === before, c.url().replace(B, '').slice(0, 60));
  } else t('stale tab refreshed itself', true);
  await b.close();
  console.log(res.every(Boolean) ? 'ALL PASS' : 'SOME FAIL');
})();
