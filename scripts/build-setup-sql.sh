#!/usr/bin/env bash
# Concatenates every migration and the seed into one file that can be pasted
# into the Supabase SQL editor in a single run.
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "-- District Five hub: full database setup. Generated by scripts/build-setup-sql.sh; do not edit."
  echo "-- Paste into Supabase → SQL editor → New query, then Run. Run it once on an empty project."
  for f in supabase/migrations/*.sql supabase/seed.sql; do echo; echo "-- ===== $f"; cat "$f"; done
} > supabase/setup.sql
echo "wrote supabase/setup.sql"
